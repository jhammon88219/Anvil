"""Generate Anvil.App/Assets/Map/county-labels.geojson — one labelled POINT per US county, for counties.js.

WHY a file of our own: the Protomaps basemap draws county BORDERS (`boundaries`, kind county) but carries no
county NAMES anywhere, so the names come from the US Census instead, bundled and offline like the states file.

Source: the Census Bureau's county GAZETTEER (public domain) —
https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_counties_national.zip
Its INTPTLAT / INTPTLONG is the Census "internal point": a point INSIDE the county (an odd-shaped county's
centre can fall outside it, this can't). Cached under tools/.cache.

    py -3 tools/make_county_labels.py                                  # download (cached) + generate
    py -3 tools/make_county_labels.py --src 2024_Gaz_counties_national.txt   # a local copy instead

Output: a FeatureCollection of Points, properties
    name  the label: the county's name WITHOUT "County" / "Parish" / "Borough" / … ("Cleveland")
    st    the state postal code ("OK") — not drawn, kept for a future tooltip / search
    area  land area in whole square miles — counties.js's symbol-sort-key (big counties win a collision)
One feature per line, sorted by state then name, so a regeneration diffs readably.

Virginia's (and a few others') INDEPENDENT CITIES are county-equivalents named "Richmond city": they are
LEFT OUT — the basemap already labels the city, and "RICHMOND" in county colour beside it would read as a
county that isn't there. ("Carson City", NV is a capitalised name, not that suffix, and stays.)

REGENERATE, NEVER EDIT the output by hand.
"""

import argparse
import io
import json
import os
import sys
import urllib.request
import zipfile

URL = "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_counties_national.zip"
TXT = "2024_Gaz_counties_national.txt"
HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, ".cache", "2024_Gaz_counties_national.zip")
OUT = os.path.join(HERE, "..", "Anvil.App", "Assets", "Map", "county-labels.geojson")

# Longest first, so "City and Borough" goes before "Borough".
SUFFIXES = [" City and Borough", " Planning Region", " Census Area", " Municipality", " Municipio",
            " Borough", " County", " Parish"]


def read_lines(src):
    if src:
        with open(src, encoding="utf-8-sig") as f:
            return f.read().splitlines()
    if not os.path.exists(CACHE):
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        print(f"downloading {URL}", file=sys.stderr)
        req = urllib.request.Request(URL, headers={"User-Agent": "Anvil-tools/1.0"})
        with urllib.request.urlopen(req) as r, open(CACHE, "wb") as f:
            f.write(r.read())
    with zipfile.ZipFile(CACHE) as z:
        name = next(n for n in z.namelist() if n.endswith(".txt"))
        with z.open(name) as f:
            return io.TextIOWrapper(f, encoding="utf-8-sig").read().splitlines()


def label_of(name):
    for s in SUFFIXES:
        if name.endswith(s):
            return name[: -len(s)]
    return name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", help=f"a local {TXT} instead of downloading")
    args = ap.parse_args()

    lines = read_lines(args.src)
    head = [h.strip() for h in lines[0].split("\t")]
    col = {h: i for i, h in enumerate(head)}
    feats = []
    skipped = 0
    for line in lines[1:]:
        c = [v.strip() for v in line.split("\t")]
        if len(c) < len(head):
            continue
        name = c[col["NAME"]]
        if name.endswith(" city"):  # an independent city (see the header)
            skipped += 1
            continue
        lat, lon = float(c[col["INTPTLAT"]]), float(c[col["INTPTLONG"]])
        area = round(float(c[col["ALAND_SQMI"]]))
        feats.append((c[col["USPS"]], label_of(name), lon, lat, area))

    feats.sort(key=lambda f: (f[0], f[1]))
    rows = []
    for st, name, lon, lat, area in feats:
        rows.append(json.dumps({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [round(lon, 4), round(lat, 4)]},
            "properties": {"name": name, "st": st, "area": area},
        }, ensure_ascii=False, separators=(",", ":")))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write('{"type":"FeatureCollection",\n"source":"US Census 2024 county gazetteer internal points; '
                'generated by tools/make_county_labels.py",\n"features":[\n')
        f.write(",\n".join(rows))
        f.write("\n]}\n")
    print(f"wrote {len(rows)} counties ({skipped} independent cities left out) -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
