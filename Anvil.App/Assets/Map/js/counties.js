// ============================================================================================
// counties.js — COUNTY NAMES: one label per US county, in a highlight colour so it reads apart from the
// basemap's own city / road / water names.
//
//   zoom < 6.5   nothing (a wall of 3,000 names)
//   zoom 6.5+    ·  CLEVELAND  ·      MCCLAIN  ·        ← UPPERCASE, letter-spaced, amber (dark theme)
//                     Norman ●               Purcell ●  ← the basemap's own city labels, unchanged
//
//   ── top ──   state isolation mask (states.js)  ← names stay UNDER it, so nothing draws outside the region
//               county-names                      ← this module, over the basemap's labels + every overlay
//               basemap labels · overlay band · basemap fills
//
// WHY a file of our own: the Protomaps tiles have county BORDERS but no county NAMES, so the points come
// from the Census gazetteer — `county-labels.geojson`, GENERATED by tools/make_county_labels.py (one point
// INSIDE each county; regenerate, never edit). Served same-origin from `mapassets`, fetched once.
//
// ON / OFF = the basemap group `county_names` (Map layers flyout → Counties → County names, beside the
// county lines). basemap.js owns that state and its apply() flips this layer's visibility along with the
// style's own layers (groupOf knows LAYER_ID), so the Map key's hide-all covers it too.
// ⚠️ LAYER_ID is mirrored in basemap.js groupOf — change both.
//
// Colliding names: the BIGGER county wins (symbol-sort-key = minus land area), so a zoomed-out view keeps
// the large western counties rather than a random pick. Colours are CHROME (theme.css tokens
// --anvil-county-name / --anvil-county-name-halo), read when the layer is added — a theme switch is a
// style switch, which re-adds it.
// ============================================================================================

import * as Theme from './theme.js';
import * as Basemap from './basemap.js';

const URL = 'https://mapassets/county-labels.geojson';
const SRC = 'county-labels';
export const LAYER_ID = 'county-names';
const GROUP = 'county_names';

// The states.js layers that must stay ABOVE the names (the isolation mask + its outline + hover).
const ABOVE = ['state-iso-fill', 'state-iso-line', 'state-iso-mask-fill', 'state-iso-mask-line'];

let data = null;      // the FeatureCollection, once fetched
let loading = null;

function load() {
    if (data || loading) return loading;
    loading = fetch(URL)
        .then(function (r) { if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); })
        .then(function (j) { data = j; return j; })
        .catch(function (e) { console.error('county labels load failed: ' + e); loading = null; });
    return loading;
}

function beforeId(map) {
    let first;
    let firstIdx = Infinity;
    const order = map.getLayersOrder ? map.getLayersOrder() : [];
    ABOVE.forEach(function (id) {
        const i = order.indexOf(id);
        if (i >= 0 && i < firstIdx) { firstIdx = i; first = id; }
    });
    return first;
}

function add(map) {
    if (!data) return;
    try {
        if (!map.getStyle()) return;
        if (!map.getSource(SRC)) map.addSource(SRC, { type: 'geojson', data: data });
        if (map.getLayer(LAYER_ID)) return;
        map.addLayer({
            id: LAYER_ID, type: 'symbol', source: SRC, minzoom: 6.5,
            layout: {
                visibility: Basemap.isGroupShown(GROUP) ? 'visible' : 'none',
                'text-field': ['get', 'name'],
                'text-font': ['Noto Sans Medium'],
                'text-transform': 'uppercase',
                'text-letter-spacing': 0.12,
                'text-size': ['interpolate', ['linear'], ['zoom'], 6.5, 10, 9, 12, 12, 14],
                'text-padding': 6,
                'text-max-width': 8,
                'symbol-sort-key': ['-', 0, ['get', 'area']],
            },
            paint: {
                'text-color': Theme.color('--anvil-county-name', '#f2b544'),
                'text-halo-color': Theme.color('--anvil-county-name-halo', 'rgba(0, 0, 0, 0.85)'),
                'text-halo-width': 1.4,
                'text-halo-blur': 0.3,
            },
        }, beforeId(map));
    } catch (e) {
        console.error('county labels add failed: ' + e);
    }
}

/** Restore onto one map (a style switch, a new pane, or the data arriving). */
export function reAdd(map) {
    if (data) { add(map); return; }
    const p = load();
    if (p) p.then(function () { add(map); });
}
